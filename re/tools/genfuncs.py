#!/usr/bin/env python3
"""Generate src/game/funcs.h: declarations of all live game functions."""
import json, re
src = open('re/out/4G.EXE.c').read()
units = json.load(open('re/units.json'))
dead = set(json.load(open('re/out/partition.json'))['unreached'])
dead -= {'FUN_0040109d','FUN_004010aa','FUN_004010b7','FUN_004010c4','FUN_004010d1','FUN_004010de',
         'FUN_004010eb','FUN_004010f8','FUN_00401105','FUN_00401112','FUN_0040111f','FUN_0040107c',
         'FUN_00402624','FUN_00402638','FUN_00402660','FUN_00402450'}
ENGINE = set()
for l in open('re/names.tsv'):
    if '\t' in l and not l.startswith('#'):
        a, n = l.split('\t')[:2]
        if int(a, 16) >= 0x41c62c or n in ('Blit_Copy',): ENGINE.add(n)
funcs = []
bodies = {}
for part in re.split(r'(?m)^// ==== ', src)[1:]:
    name, rest = part.split(' @ ', 1)
    a = int(rest[:8], 16)
    body = part.split('\n', 1)[1]
    bodies[name] = body
    if a >= 0x41c62c or name in dead or 0x40189b <= a < 0x402450: continue
    sig = ''
    for l in body.split('\n'):
        if not l.strip() or l.strip().startswith('/*'): continue
        sig += l.strip() + ' '
        if ')' in l: break
    funcs.append((a, name, sig.strip()))
# callbacks: referenced without a call
cb = set()
for b in bodies.values():
    for m in re.finditer(r'\b(FUN_[0-9a-f]{8})\b(?!\s*\()', b):
        cb.add(m.group(1))
def ctype(t):
    t = t.replace('__cdecl', '').replace('__stdcall', '').strip()
    ptr = t.count('*')
    base = t.replace('*', '').strip()
    m = {'void': 'void', 'undefined4': 'int', 'int': 'int', 'uint': 'u32', 'undefined': 'int', 'ushort': 'u16',
         'short': 's16', 'undefined2': 's16', 'byte': 'u8', 'undefined1': 'u8', 'char': 'char', 'bool': 'bool',
         'LPVOID': 'void*', 'LPCVOID': 'const void*', 'LPCSTR': 'const char*', 'HFILE': 'int', 'SIZE_T': 'u32',
         'longlong': 's64', 'ulonglong': 'u64', 'BOOL': 'int', 'UINT': 'u32', 'DWORD': 'u32'}
    b = m.get(base, None)
    if b is None: b = 'int'
    if ptr:
        if b in ('void', 'int', 'u32', 'u8', 's16', 'u16') and base.startswith('undefined'): b = 'void'
        return b + '*' * ptr
    return b
out = ['// Generated by re/tools/genfuncs.py from the decompilation: declarations of',
       '// every live game function in 4G.EXE (0x401000..0x41c62c). The owning unit',
       '// (see re/units.json) implements each one; keep signatures in sync.',
       '#pragma once', '#include "engine/core.h"', '']
for a, name, sig in sorted(funcs):
    m = re.match(r'(.*?)\b' + re.escape(name) + r'\s*\((.*)\)', sig)
    if not m: continue
    ret = ctype(m.group(1))
    params = m.group(2).strip()
    plist = []
    if params not in ('', 'void'):
        for i, p in enumerate(params.split(',')):
            p = p.strip()
            pm = re.match(r'(.*?)(\w+)$', p)
            plist.append(ctype(pm.group(1)) + ' ' + pm.group(2))
    if name in cb and len(plist) == 1:
        ret, plist = 'int', ['int ev']
    unit = next((u for u, rs in units.items() if any(int(lo, 16) <= a < int(hi, 16) for lo, hi in rs)), '?')
    out.append(f"{ret} {name}({', '.join(plist)});{' ' * max(1, 60 - len(ret) - len(name) - len(', '.join(plist)))}// {unit}{' callback' if name in cb else ''}")
open('src/game/funcs.h', 'w').write('\n'.join(out) + '\n')
print(len(funcs), 'functions')
