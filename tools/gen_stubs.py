#!/usr/bin/env python3
"""Generate src/game/zz_stubs.cpp with aborting stubs for every declared game
function that no unit defines yet (lets the app link while porting)."""
import glob, re, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
decls = {}
for h in glob.glob(os.path.join(root, 'src/game/decl/*.h')):
    for line in open(h):
        m = re.match(r'\s*([\w\s\*]+?)\s*\b(FUN_[0-9a-f]{8})\s*\(([^)]*)\)\s*;', line)
        if m: decls[m.group(2)] = (m.group(1).strip(), m.group(3).strip())
import sys
only = sys.argv[1:]
defined = set()
files = [os.path.join(root, 'src/game', u + '.cpp') for u in only] if only else glob.glob(os.path.join(root, 'src/game/*.cpp'))
for c in files:
    if c.endswith('zz_stubs.cpp'): continue
    src = open(c).read()
    for m in re.finditer(r'^[\w\s\*]*?\b(FUN_[0-9a-f]{8})\s*\([^;{]*\)\s*\{', src, re.M):
        defined.add(m.group(1))
out = ['// Generated by tools/gen_stubs.py: placeholders for unported functions.',
       '#include <cstdio>', '#include <cstdlib>', '#include "game/common.h"', '']
n = 0
for name, (ret, params) in sorted(decls.items()):
    if name in defined: continue
    n += 1
    body = f'{{ fprintf(stderr, "unported function {name}\\n"); abort(); }}'
    out.append(f'{ret} {name}({params}) {body}')
open(os.path.join(root, 'src/game/zz_stubs.cpp'), 'w').write('\n'.join(out) + '\n')
print(n, 'stubs')
